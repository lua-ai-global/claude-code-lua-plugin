#!/usr/bin/env node
import { build } from 'esbuild';
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

// EM-WS8 (1.6.0): EVERYTHING is bundled, `@modelcontextprotocol/sdk` included.
// The plugin ships no node_modules — marketplace installs copy the directory
// verbatim and the Lua Job tier bakes it into an image the same way — so an
// external SDK made the server die with ERR_MODULE_NOT_FOUND on every install
// (Claude Code shows it as `lua-platform CONNECTION_CLOSED`).
// tests/standalone-bundle.test.mjs copies dist/server.js into an empty temp
// directory and lists the tools over stdio to keep it that way.
//
// Iteration-13 audit: `packages: 'bundle'` is not used — that option only
// exists in esbuild >=0.22 and the pinned dep is `^0.20.0`; `bundle: true`
// with no `external` already bundles every npm import. Node builtins stay
// external automatically (`platform: 'node'`).
//
// The banner gives the ESM bundle a real `require`, so any CommonJS module
// the SDK pulls in can still `require()` a node builtin.
//
// Licences: the bundle redistributes third-party code, so the build also
// writes dist/THIRD_PARTY_NOTICES.txt — every npm package esbuild actually
// pulled in (from the metafile), with its version, licence and full licence
// text — and keeps any `/*! … */` legal comments at the end of the bundle.
const result = await build({
  entryPoints: ['src/server.mjs'],
  bundle: true,
  platform: 'node',
  target: 'node18',
  format: 'esm',
  banner: {
    js: "import { createRequire as __luaCreateRequire } from 'node:module'; const require = __luaCreateRequire(import.meta.url);",
  },
  minify: true,
  legalComments: 'eof',
  metafile: true,
  sourcemap: 'inline',
  outfile: 'dist/server.js',
});

/** node_modules/<name or @scope/name>/… → package directory, for every bundled input. */
const packageDirs = new Set();
for (const input of Object.keys(result.metafile.inputs)) {
  const m = /^(.*?node_modules\/(?:@[^/]+\/)?[^/]+)\//.exec(input.replace(/\\/g, '/'));
  if (m) packageDirs.add(m[1]);
}

const LICENCE_FILE = /^(?:licen[cs]e|copying|notice)(?:[.-].*)?$/i;
const sections = [...packageDirs].sort().map((dir) => {
  const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
  const licence = typeof pkg.license === 'string' ? pkg.license : pkg.license?.type ?? 'UNKNOWN';
  const files = existsSync(dir) ? readdirSync(dir).filter((f) => LICENCE_FILE.test(f)).sort() : [];
  const texts = files.map((f) => readFileSync(join(dir, f), 'utf8').trim());
  return [
    `${pkg.name}@${pkg.version} — ${licence}`,
    pkg.repository ? `Source: ${typeof pkg.repository === 'string' ? pkg.repository : pkg.repository.url}` : null,
    '',
    texts.length ? texts.join('\n\n') : `(No licence file ships with the package; its package.json declares ${licence}.)`,
  ].filter((l) => l !== null).join('\n');
});

writeFileSync(
  'dist/THIRD_PARTY_NOTICES.txt',
  'Third-party software bundled into dist/server.js (@lua/claude-plugin-mcp).\n' +
    'Generated by scripts/bundle.mjs from the esbuild metafile; do not edit by hand.\n\n' +
    sections.join('\n\n' + '-'.repeat(78) + '\n\n') + '\n',
);

console.log(`✓ Bundled to dist/server.js (self-contained, no runtime node_modules needed); ${packageDirs.size} third-party package(s) listed in dist/THIRD_PARTY_NOTICES.txt`);
